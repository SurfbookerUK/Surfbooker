// Writes the client-side destination lists used by the homepage map and destination finder.
// Generated from data/destinations/*.mjs so names, URLs, descriptions and images always match
// the guides. Each destination carries its OWN licensed photo (or none) — never a stock tile.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadDestinations } from "./build-destination-guides.mjs";

const root = process.cwd();
const derivatives = JSON.parse(readFileSync(join(root, "data/image-derivatives.json"), "utf8"));
const all = await loadDestinations();

const mapRegion = { "north-devon": "devon", "south-devon": "devon", "northeast-england-yorkshire": "northeast" };
const thumb = (path) => {
  const files = derivatives[path]?.files;
  if (!files?.length) return null;
  const sorted = [...files].sort((a, b) => a.width - b.width);
  const pick = sorted.find((f) => f.width >= 480) || sorted.at(-1);
  return "/" + pick.file.replace(/^\//, "");
};

const entry = (d) => ({
  title: d.fullName && d.fullName.length < 28 ? d.fullName : d.name,
  region: mapRegion[d.region] || d.region,
  lat: d.geo?.[0],
  lng: d.geo?.[1],
  description: d.heroIntro,
  url: d.path,
  image: thumb(d.images?.hero || d.images?.feature?.path || "") || null
});

const list = [
  { title: "Westward Ho!", region: "devon", lat: 51.039, lng: -4.238, description: "Surfbooker's home beach — two miles of sand, the pebble ridge and a choice of surf schools.", url: "/guides/westwardho!/", image: thumb("guides/westwardho!/beach-front.jpg") },
  ...all.filter((d) => d.geo).map(entry)
];

writeFileSync(join(root, "surf-destinations.js"), `// Generated by scripts/build-destination-data.mjs — do not edit by hand.\nwindow.surfbookerAllDestinations=${JSON.stringify(list)};\n`);
// The homepage keeps its own hand-maintained scotland/northeast/northern-ireland/southern-england
// destination files, so this script only writes surf-destinations.js.
console.log(`Destination data written: ${list.length} destinations.`);
